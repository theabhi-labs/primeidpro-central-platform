const Center = require('../models/Center');
const PricingRule = require('../models/PricingRule');
const CreditPackage = require('../models/CreditPackage');
const ApiResponse = require('../utils/apiResponse');

class PublicController {
  /**
   * Resolve public QR token to center and service details
   * GET /api/v1/public/qr/:qrToken
   */
  async resolveQr(req, res) {
    try {
      const { qrToken } = req.params;

      const center = await Center.findOne({
        $or: [
          { qrToken },
          { slug: qrToken.toLowerCase() },
          { centerCode: qrToken.toUpperCase() },
          { _id: qrToken.match(/^[0-9a-fA-F]{24}$/) ? qrToken : null }
        ],
        status: 'ACTIVE'
      });
      if (!center) {
        return ApiResponse.error(res, 'This QR code is invalid, expired, or has been regenerated by the center', 404);
      }

      return ApiResponse.success(res, {
        centerId: center._id,
        centerName: center.centerName,
        centerCode: center.centerCode,
        slug: center.slug,
        address: center.address,
        city: center.city,
        phone: center.phone,
        serviceSettings: center.serviceSettings
      }, 'Center details resolved');
    } catch (err) {
      return ApiResponse.error(res, err.message, 500);
    }
  }

  /**
   * Public list of service templates
   * GET /api/v1/public/templates
   */
  async getTemplates(req, res) {
    try {
      const templates = await PricingRule.find({ active: true }).lean();
      return ApiResponse.success(res, templates, 'Templates retrieved');
    } catch (err) {
      return ApiResponse.error(res, err.message, 500);
    }
  }

  /**
   * Public list of credit packages
   * GET /api/v1/public/packages
   */
  async getPackages(req, res) {
    try {
      let packages = await CreditPackage.find({ active: true }).sort({ displayOrder: 1, price: 1 }).lean();
      if (packages.length === 0) {
        packages = [
          { _id: 'pkg_100', name: 'Starter Pack', price: 100, credits: 100, active: true },
          { _id: 'pkg_500', name: 'Growth Pack', price: 500, credits: 550, active: true },
          { _id: 'pkg_1000', name: 'Studio Pro', price: 1000, credits: 1150, active: true },
          { _id: 'pkg_2000', name: 'Enterprise Hub', price: 2000, credits: 2400, active: true }
        ];
      }
      return ApiResponse.success(res, packages, 'Packages retrieved');
    } catch (err) {
      return ApiResponse.error(res, err.message, 500);
    }
  }
}

module.exports = new PublicController();
